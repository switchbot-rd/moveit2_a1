#!/usr/bin/env python3
"""Generate left single-arm and dual-arm descriptions from SDK A1L/A1R models."""
import argparse
from copy import deepcopy
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET

try:
    from tools.collision_meshes import apply_collision_meshes
except ModuleNotFoundError:
    from collision_meshes import apply_collision_meshes

XACRO = 'http://www.ros.org/wiki/xacro'
ET.register_namespace('xacro', XACRO)
ROOT = Path(__file__).resolve().parent.parent


def xacro(tag, **attributes):
    return ET.Element(f'{{{XACRO}}}{tag}', attributes)


def prefixed(element, *, joints=False):
    item = deepcopy(element)
    if item.tag == 'link' or (item.tag == 'joint' and joints):
        item.set('name', '${prefix}'+item.get('name'))
    for e in item.iter():
        for key in ('link', 'link1', 'link2'):
            if key in e.attrib:
                e.set(key, '${prefix}'+e.get(key))
        if joints and e.tag == 'mimic':
            e.set('joint', '${prefix}'+e.get('joint'))
    return item


def write(root, path):
    ET.indent(root, space='  ')
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('<?xml version="1.0"?>\n<!-- Generated by tools/sync_dual_description_from_sdk.py. -->\n'
                    + ET.tostring(root, encoding='unicode')+'\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk-root', type=Path, required=True)
    args = parser.parse_args()
    sdk = args.sdk_root/'onero_sdk'
    macro = ET.Element('robot')
    semantic = ET.Element('robot', {'name': 'onero_a1'})
    semantic.append(xacro('arg', name='gripper_model', default='woan_picker'))
    ET.SubElement(semantic, 'virtual_joint', name='world_joint', type='fixed',
                  parent_frame='world', child_link='base_link')
    both = ET.SubElement(semantic, 'group', name='both_arms')
    for side, suffix in (('left', 'l'), ('right', 'r')):
        source = sdk/'urdf/A1'/f'a1_{suffix}.urdf'
        model = ET.parse(source).getroot()
        body = xacro('macro', name=f'onero_a1_{side}_body', params='prefix')
        macro.append(body)
        group = ET.SubElement(semantic, 'group', name=f'{side}_arm')
        ET.SubElement(group, 'chain', base_link=f'{side}_base_link', tip_link=f'{side}_Link7')
        ET.SubElement(both, 'group', name=f'{side}_arm')
        for element in model:
            # A1L has an identity virtual world root. Installation belongs to
            # the shared dual-arm root; preserve the seven physical joints.
            if element.tag == 'link' and element.get('name') == 'world':
                continue
            if element.tag == 'joint' and element.find('parent').get('link') == 'world':
                assert element.get('type') == 'fixed'
                assert element.find('child').get('link') == 'base_link'
                origin = element.find('origin')
                assert all(float(v) == 0 for k in ('xyz', 'rpy') for v in origin.get(k, '0 0 0').split())
                continue
            if element.tag not in ('link', 'joint'):
                continue
            copy = prefixed(element)
            for mesh in copy.iter('mesh'):
                name = Path(mesh.get('filename').replace('\\', '/')).name
                mesh.set('filename', f'package://onero_a1_description/meshes/A1_{suffix}/{name}')
                src = sdk/'meshes/A1'/f'A1_{suffix}'/name
                dst = ROOT/'src/onero_a1_description/meshes'/f'A1_{suffix}'/name
                dst.parent.mkdir(parents=True, exist_ok=True)
                if not dst.exists() or dst.read_bytes() != src.read_bytes():
                    shutil.copyfile(src, dst)
            body.append(copy)
            if element.tag == 'joint':
                # Only names and mesh URIs may change; preserve physical data.
                for tag in ('origin', 'axis', 'limit'):
                    assert ET.tostring(element.find(tag)) == ET.tostring(copy.find(tag))
                ET.SubElement(semantic, 'disable_collisions',
                              link1=side+'_'+element.find('parent').get('link'),
                              link2=side+'_'+element.find('child').get('link'), reason='Adjacent')
        ET.SubElement(semantic, 'disable_collisions', link1='base_link', link2=side+'_base_link', reason='Adjacent')
        for name, values in (('home', [0.]*7), ('ready', [0., 1., 0., 1.5, 0., -.5, 0.]
                              if side == 'left' else [0., -1., 0., -1.5, 0., .5, 0.])):
            state = ET.SubElement(semantic, 'group_state', name=name, group=side+'_arm')
            for i, value in enumerate(values, 1):
                ET.SubElement(state, 'joint', name=f'joint{i}-a1_{suffix}', value=str(value))

    semantic.append(ET.Comment(
        '仅适用于本项目已确认的固定安装：左右 Link1–Link4 永不互碰；调整安装后需重新核实。'))
    for left in range(1, 5):
        for right in range(1, 5):
            ET.SubElement(semantic, 'disable_collisions',
                          link1=f'left_Link{left}', link2=f'right_Link{right}', reason='Never')

    gripper = xacro('macro', name='onero_dual_woan_picker', params='prefix')
    for element in ET.parse(ROOT/'src/onero_a1_description/urdf/onero_woan_picker.urdf').getroot():
        gripper.append(prefixed(element, joints=True))
    macro.append(gripper)
    conditional = xacro('if', value="${'$(arg gripper_model)' == 'woan_picker'}")
    semantic.append(conditional)
    both_grippers = ET.SubElement(conditional, 'group', name='both_grippers')
    for side in ('left', 'right'):
        ET.SubElement(both_grippers, 'group', name=side+'_gripper')
    gripper_semantic = ET.parse(ROOT/'src/onero_a1_moveit_config/config/onero_woan_picker.srdf').getroot()
    for side in ('left', 'right'):
        prefix = side+'_'
        for source in gripper_semantic:
            element = deepcopy(source)
            for e in element.iter():
                for key in ('name', 'group', 'parent_group', 'parent_link', 'link1', 'link2'):
                    if key in e.attrib and not (e.tag == 'group_state' and key == 'name'):
                        e.set(key, prefix+e.get(key))
            conditional.append(element)
    for name in ('home', 'ready'):
        state = ET.SubElement(semantic, 'group_state', name=name, group='both_arms')
        for side in ('left', 'right'):
            source = semantic.find(f"group_state[@name='{name}'][@group='{side}_arm']")
            state.extend(deepcopy(list(source)))
    apply_collision_meshes(macro, ROOT/'src/onero_a1_description')
    write(macro, ROOT/'src/onero_a1_description/urdf/onero_a1_arms.urdf.xacro')
    write(semantic, ROOT/'src/onero_a1_moveit_config/config/onero_a1_dual.srdf.xacro')
    single = ET.Element('robot', name='onero_a1')
    arm = ET.SubElement(single, 'group', name='arm')
    ET.SubElement(arm, 'chain', base_link='base_link', tip_link='Link7')
    ET.SubElement(single, 'virtual_joint', name='world_joint', type='fixed', parent_frame='world', child_link='base_link')
    for source in semantic.findall("group_state[@group='left_arm']"):
        state = deepcopy(source); state.set('group', 'arm'); single.append(state)
    for joint in ET.parse(sdk/'urdf/A1/a1_l.urdf').getroot().findall('joint'):
        if joint.find('parent').get('link') != 'world':
            ET.SubElement(single, 'disable_collisions', link1=joint.find('parent').get('link'),
                          link2=joint.find('child').get('link'), reason='Adjacent')
    write(single, ROOT/'src/onero_a1_moveit_config/config/onero_a1_left.srdf')
    print('已生成左右臂模型、夹爪及双臂 SRDF；SDK 文件未写入。')


if __name__ == '__main__':
    main()
