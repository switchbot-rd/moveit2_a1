#!/usr/bin/env python3
"""Import the SDK's Woan Picker geometry/coupling without changing the SDK."""
import argparse
from copy import deepcopy
import hashlib
import json
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET


def main():
    import onero_sdk
    from onero_sdk.tool_models import get_tool_model
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sdk-root', type=Path, default=Path(onero_sdk.__file__).parent)
    args = parser.parse_args()
    workspace = Path(__file__).resolve().parents[1]
    description = workspace / 'src/onero_a1_description'
    config = workspace / 'src/onero_a1_moveit_config/config'
    spec = get_tool_model('woan_picker')
    source = args.sdk_root / 'tools' / spec['urdf']
    root = ET.fromstring(source.read_text())
    master = 'woan_picker_left_finger_joint'
    scales = {'woan_picker_' + j['suffix']: j['scale'] for j in spec['opening_joints']}
    hashes = {}
    for link in root.findall('link'):
        for visual in link.findall('visual'):
            mesh = visual.find('geometry/mesh')
            src = args.sdk_root / mesh.get('filename')
            dest = description / mesh.get('filename')
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(src, dest)
            hashes[mesh.get('filename')] = hashlib.sha256(src.read_bytes()).hexdigest()
            mesh.set('filename', 'package://onero_a1_description/' + mesh.get('filename'))
            collision = ET.SubElement(link, 'collision')
            for tag in ('origin', 'geometry'):
                e = visual.find(tag)
                if e is not None:
                    collision.append(deepcopy(e))
    for joint in root.findall('joint'):
        name = joint.get('name')
        # Adapter rate cap: <= 0.5 normalized opening per second. Not a motor specification.
        joint.find('limit').set('velocity', str(scales[name] * .5))
        if name != master:
            ET.SubElement(joint, 'mimic', joint=master, multiplier=str(scales[name] / scales[master]), offset='0')
    mount = ET.SubElement(root, 'joint', name='woan_picker_mount', type='fixed')
    ET.SubElement(mount, 'parent', link='Link7')
    ET.SubElement(mount, 'child', link='woan_picker_base_link')
    ET.SubElement(mount, 'origin', xyz=' '.join(map(str, spec['mount_xyz'])), rpy=' '.join(map(str, spec['mount_rpy'])))
    ET.indent(root, space='  ')
    out = description / 'urdf/onero_woan_picker.urdf'
    out.write_text('<?xml version="1.0"?>\n<!-- Generated by tools/sync_woan_picker_from_sdk.py; SDK geometry and mounting retained. -->\n' + ET.tostring(root, encoding='unicode') + '\n')
    semantic = ET.Element('robot', name='onero_a1')
    group = ET.SubElement(semantic, 'group', name='gripper')
    for link in root.findall('link'):
        ET.SubElement(group, 'link', name=link.get('name'))
    ET.SubElement(semantic, 'end_effector', name='woan_picker', parent_link='Link7', group='gripper', parent_group='arm')
    for name, value in [('closed', 0), ('open', 1.1)]:
        state = ET.SubElement(semantic, 'group_state', name=name, group='gripper')
        ET.SubElement(state, 'joint', name=master, value=str(value))
    for joint in root.findall('joint'):
        ET.SubElement(semantic, 'disable_collisions', link1=joint.find('parent').get('link'), link2=joint.find('child').get('link'), reason='Adjacent')
    # Wrist housing and picker base form the output-flange mounting interface.
    # Their CAD clearance stays about 0.05 mm throughout joint7 travel; treating
    # it as an obstacle otherwise scales every Servo command almost to zero.
    ET.SubElement(semantic, 'disable_collisions', link1='Link6', link2='woan_picker_base_link', reason='Mounting')
    # Closing pin of each four-bar mechanism is not representable as a URDF tree edge.
    for side in ('left', 'right'):
        ET.SubElement(semantic, 'disable_collisions', link1=f'woan_picker_{side}_finger_link_3', link2=f'woan_picker_{side}_finger_link_4', reason='Mechanism')
    # Opposing jaw pads touch at the calibrated fully closed endpoint.
    ET.SubElement(semantic, 'disable_collisions', link1='woan_picker_left_finger_link_3',
                  link2='woan_picker_right_finger_link_3', reason='FingerContact')
    ET.indent(semantic, space='  ')
    (config / 'onero_woan_picker.srdf').write_text('<?xml version="1.0"?>\n<!-- Generated by tools/sync_woan_picker_from_sdk.py. -->\n' + ET.tostring(semantic, encoding='unicode') + '\n')
    (description / 'urdf/woan_picker_source.json').write_text(json.dumps({'source': 'onero-sdk/tools/woan_picker.urdf', 'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'tool_model': spec, 'mesh_sha256': hashes}, ensure_ascii=False, indent=2) + '\n')
    print(f'Imported Woan Picker: {len(hashes)} meshes, 8 coupled joints, mount={spec["mount_xyz"]}/{spec["mount_rpy"]}')


if __name__ == '__main__':
    main()
